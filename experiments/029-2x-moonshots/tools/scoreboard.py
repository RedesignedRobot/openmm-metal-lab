"""SCOREBOARD.md from a window's result.json (summarize.py writes it; window.sh runs summarize.py).

usage: python3 scoreboard.py <window outdir> [--ref TREE] [-o FILE]
Reads <outdir>/ab/result.json (or <outdir>/result.json) and prints the scoreboard: every Metal arm against
the OpenCL arm per test with the 2x count, the rows still under 2x and the step-time cut each needs, every other
tree against the reference tree (--ref, default the first Metal tree in configs.txt) at the same precision with
its per-round range, power, run hygiene, and the arms' commits. A tree is a label without its -single, -mixed or
-opencl suffix. -o writes FILE (atomically) instead of printing. A person adds judgment (levers, verdicts) below
the generated part; rerunning overwrites the file.
"""
import json
import os
import statistics
import sys

MISSION = 2.0
SPREAD_FLAG = 0.015
TEST_NAMES = {"amber20-dhfr": "dhfr", "amber20-cellulose": "cellulose", "amber20-stmv": "stmv"}


def load(outdir):
    for path in (os.path.join(outdir, "ab", "result.json"), os.path.join(outdir, "result.json")):
        if os.path.exists(path):
            return path, json.load(open(path))
    sys.exit(f"no result.json in {outdir} or {outdir}/ab: run summarize.py on it first")


def tree_of(label):
    return label.rsplit("-", 1)[0] if label.rsplit("-", 1)[-1] in ("single", "mixed", "opencl") else label


def table(header, rows):
    lines = ["| " + " | ".join(header) + " |", "|" + "---|" * len(header)]
    return lines + ["| " + " | ".join(row) + " |" for row in rows]


def board(outdir, result, source, ref=None):
    rows = {(r["test"], r["label"]): r for r in result["rows"]}
    tests = list(dict.fromkeys(r["test"] for r in result["rows"]))
    arms = result.get("arms", {})
    labels = list(arms) or list(dict.fromkeys(r["label"] for r in result["rows"]))
    opencl = [l for l in labels if arms.get(l, {}).get("platform") == "OpenCL"]
    metal = [l for l in labels if arms.get(l, {}).get("platform") == "Metal"]
    trees = list(dict.fromkeys(tree_of(l) for l in metal))
    ref = ref or (trees[0] if trees else None)
    rounds = max((len(r["rounds"]) for r in result["rows"]), default=0)
    hy = result.get("hygiene", {})
    job = result.get("gpuq_job")

    def ratio(test, num, den):
        a, b = rows.get((test, num)), rows.get((test, den))
        if not a or not b:
            return None
        per_round = [a["rounds"][r] / b["rounds"][r] for r in a["rounds"] if r in b["rounds"]]
        return a["median"] / b["median"], min(per_round), max(per_round)

    out = [f"# 029 scoreboard, {result.get('last_run') or result.get('written')} ({os.path.basename(outdir.rstrip('/'))})", "",
           f"Generated by scoreboard.py from {source}. {(result.get('slot') or 'unknown').capitalize()} slot, "
           f"{rounds} interleaved rounds, {len(tests)} tests"
           + (f", gpuq job {job}" if job else "") + f". Clock: {result['clock']}.", ""]
    if opencl:
        den = opencl[0]
        a = arms.get(den, {})
        out += [f"## Metal / OpenCL", "",
                f"Denominator: {den} ({a.get('tree')}, commit {(a.get('commit') or '?')[:9]}), same session.", ""]
        cells = {(t, l): ratio(t, l, den) for t in tests for l in metal}
        out += table(["test"] + metal, [[TEST_NAMES.get(t, t)] + [f"{c[0]:.3f}" if (c := cells[(t, l)]) else ""
                                                                   for l in metal] for t in tests])
        out.append("")
        under = []
        for l in metal:
            got = [cells[(t, l)] for t in tests if cells[(t, l)]]
            out.append(f"- {l}: {sum(c[0] >= MISSION for c in got)} of {len(got)} at or over {MISSION:g}x.")
            under += [(l, t, cells[(t, l)][0]) for t in tests if cells[(t, l)] and cells[(t, l)][0] < MISSION]
        out.append("")
        if under:
            out += ["Rows under 2x and the step-time cut each needs:", ""]
            out += table(["arm", "test", "Metal/OpenCL", "step cut needed"],
                         [[l, TEST_NAMES.get(t, t), f"{r:.3f}", f"{100 * (1 - r / MISSION):.1f}%"] for l, t, r in under])
            out.append("")
    others = [t for t in trees if t != ref]
    if ref and others:
        pairs = [(f"{t}-{p}", f"{ref}-{p}") for t in others for p in ("single", "mixed")
                 if f"{t}-{p}" in metal and f"{ref}-{p}" in metal]
        if pairs:
            out += [f"## Against {ref}, same precision", ""]
            out += table(["test"] + [f"{n}/{d}" for n, d in pairs],
                         [[TEST_NAMES.get(t, t)] + [f"{c[0]:.3f} ({c[1]:.3f}..{c[2]:.3f})" if (c := ratio(t, n, d)) else ""
                                                    for n, d in pairs] for t in tests])
            out += ["", "Each cell is the median ratio, then the lowest and highest single-round ratio.", ""]
    power = {(p["test"], p["label"]): p for p in result.get("power", [])}
    if power:
        out += ["## Power (gpuclock, GPU-busy seconds, median over rounds)", ""]
        plabels = [l for l in labels if any((t, l) in power for t in tests)]
        for key, what, digits in (("gpu_w", "GPU W", 1), ("ns_per_day_per_gpu_w", "ns/day per GPU W", 2)):
            out += [f"{what}:", ""]
            out += table(["test"] + plabels, [[TEST_NAMES.get(t, t)] + [f"{power[(t, l)][key]:.{digits}f}"
                                                                       if (t, l) in power else "" for l in plabels]
                                              for t in tests])
            out.append("")
        for l in metal:
            if opencl:
                eff = [power[(t, l)]["ns_per_day_per_gpu_w"] / power[(t, opencl[0])]["ns_per_day_per_gpu_w"]
                       for t in tests if (t, l) in power and (t, opencl[0]) in power]
                if eff:
                    out.append(f"- {l}: {min(eff):.2f}x to {max(eff):.2f}x OpenCL's ns/day per GPU W over {len(eff)} tests.")
        out.append("")
    spread = [r for r in result["rows"] if r["spread"] > SPREAD_FLAG]
    out += ["## Run hygiene", "",
            f"- {hy.get('runs', '?')} runs, {len(hy.get('no_result', []))} with no result, "
            f"{len(hy.get('build_overlap', []))} overlapping a build, {len(hy.get('cpu_busy', []))} CPU runs beside a busy process."]
    for key, what in (("foreign_gpu", "FOREIGN GPU (another process on the GPU before or after the run)"),
                      ("vm_high", "Background VM CPU at 90% or more"), ("no_result", "no result"),
                      ("build_overlap", "overlapping a build")):
        lines = hy.get(key, [])
        if lines:
            out.append(f"- {len(lines)} {what}:")
            out += [f"  - {line}" for line in lines]
    if hy.get("load"):
        out.append(f"- 1 minute load {hy['load'][0]:.2f} to {hy['load'][1]:.2f}"
                   + (f"; Background VM CPU {hy['vm_cpu'][0]}% to {hy['vm_cpu'][1]}%." if hy.get("vm_cpu") else "."))
    out.append(f"- {len(spread)} rows with a spread over {100 * SPREAD_FLAG:g}%"
               + (": " + ", ".join(f"{r['label']} {TEST_NAMES.get(r['test'], r['test'])} {100 * r['spread']:.1f}%"
                                   for r in spread) + "." if spread else "."))
    out += ["", "## Arms", ""]
    out += table(["label", "tree", "commit", "src"],
                 [[l, a.get("tree") or "", (a.get("commit") or "")[:9], (a.get("src") or "")[:10]] for l, a in arms.items()])
    return "\n".join(out) + "\n"


def main():
    args = sys.argv[1:]
    ref = out_path = None
    while len(args) > 1 and args[-2] in ("--ref", "-o"):
        flag, value = args[-2:]
        args = args[:-2]
        ref, out_path = (value, out_path) if flag == "--ref" else (ref, value)
    if len(args) != 1 or not os.path.isdir(args[0]):
        sys.exit(__doc__)
    source, result = load(args[0])
    text = board(args[0], result, source, ref)
    if not out_path:
        sys.stdout.write(text)
        return
    with open(out_path + ".new", "w") as f:
        f.write(text)
    os.replace(out_path + ".new", out_path)


if __name__ == "__main__":
    main()
